class TikTok4LetterFinder:
    def __init__(self, delay: float = 0.3):
        self.delay = delay
        self.checked_count = 0
        self.available_usernames = []
        self.error_count = 0
        
    def get_random_user_agent(self) -> str:
        return random.choice(USER_AGENTS)
    
    def generate_4_letter_usernames(self, start_index=0, count=None) -> List[str]:
        """Generate 4-letter combinations with all lowercase letters"""
        chars = string.ascii_lowercase
        all_combinations = itertools.product(chars, repeat=4)
        
        if count:
            for _ in range(start_index):
                next(all_combinations, None)
            return [''.join(combo) for combo, _ in zip(all_combinations, range(count))]
        else:
            return [''.join(combo) for combo in all_combinations]
    
    def check_username(self, username: str) -> bool:
        """
        Check if a TikTok username is available
        Returns: True if available, False if taken or error
        """
        url = f"https://www.tiktok.com/@{username}"
        
        headers = {
            'User-Agent': self.get_random_user_agent(),
            'Accept': 'text/html,application/xhtml+xml,application/xml;q=0.9,image/avif,image/webp,*/*;q=0.8',
            'Accept-Language': 'en-US,en;q=0.9',
            'Accept-Encoding': 'gzip, deflate, br',
            'Connection': 'keep-alive',
            'Upgrade-Insecure-Requests': '1',
            'Sec-Fetch-Dest': 'document',
            'Sec-Fetch-Mode': 'navigate',
            'Sec-Fetch-Site': 'none',
            'Sec-Fetch-User': '?1',
            'Cache-Control': 'max-age=0',
            'DNT': '1'
        }
        
        try:
            response = requests.get(url, headers=headers, timeout=10, allow_redirects=True)
            self.checked_count += 1
            
            status_code = response.status_code
            content = response.text.lower()
            
            available = False
            
            if status_code == 404:
                available = True
            elif status_code == 200:
                if any(phrase in content for phrase in [
                    "couldn't find this account",
                    "user not found",
                    "page not available",
                    "this account doesn't exist",
                    "account not found",
                    '"statusCode":10202',
                    '"statusCode":10201',
                ]):
                    available = True
            
            if available:
                self.available_usernames.append(username)
                print(f"🎉 AVAILABLE: @{username}")
                
            if self.checked_count % 50 == 0:
                print(f"[Progress] Checked: {self.checked_count} | Found: {len(self.available_usernames)}")
            
            time.sleep(self.delay)
            return available
            
        except requests.exceptions.RequestException as e:
            self.error_count += 1
            if self.error_count % 10 == 0:
                print(f"[Warning] Errors: {self.error_count}")
            time.sleep(self.delay * 2)
            return False
    
    def check_batch_parallel(self, usernames: List[str], max_workers: int = 5):
        """Check multiple usernames in parallel"""
        with ThreadPoolExecutor(max_workers=max_workers) as executor:
            futures = {executor.submit(self.check_username, username): username for username in usernames}
            
            for future in as_completed(futures):
                try:
                    future.result()
                except Exception as e:
                    print(f"[Error] {str(e)}")
    
    def save_available_usernames(self, filename: str = 'available_4letter_usernames.txt'):
        """Save available usernames to a text file"""
        if self.available_usernames:
            with open(filename, 'w') as f:
                for username in sorted(self.available_usernames):
                    f.write(f"@{username}\n")
            print(f"\n✓ Saved {len(self.available_usernames)} available usernames to {filename}")
        
        return self.available_usernames


